-- PROJETO ELEGIA - PostgreSQL + pgvector
-- Dados sintéticos para fins acadêmicos. Ajuste tipos, políticas e índices
-- conforme volume, requisitos legais e versão instalada do PostgreSQL/pgvector.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE partido (
    id_partido       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_partido   INTEGER NOT NULL UNIQUE CHECK (numero_partido > 0),
    sigla            VARCHAR(20) NOT NULL UNIQUE,
    nome_completo    VARCHAR(200) NOT NULL
);

CREATE TABLE candidatura (
    id_candidatura   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf_candidato    CHAR(11) NOT NULL UNIQUE,
    nome_completo    VARCHAR(200) NOT NULL,
    genero           CHAR(1) NOT NULL CHECK (genero IN ('M', 'F', 'O')),
    cargo_pretendido VARCHAR(100) NOT NULL,
    total_votos      INTEGER NOT NULL DEFAULT 0 CHECK (total_votos >= 0),
    id_partido       BIGINT NOT NULL REFERENCES partido(id_partido)
                     ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_candidatura_cpf_digitos CHECK (cpf_candidato ~ '^[0-9]{11}$')
);

CREATE TABLE despesa_campanha (
    id_despesa          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidatura      BIGINT NOT NULL REFERENCES candidatura(id_candidatura)
                        ON UPDATE RESTRICT ON DELETE RESTRICT,
    documento_fornecedor VARCHAR(14) NOT NULL,
    nome_fornecedor     VARCHAR(200) NOT NULL,
    valor_despesa       NUMERIC(14,2) NOT NULL CHECK (valor_despesa >= 0),
    data_contratacao    DATE NOT NULL,
    texto_bruto         TEXT NOT NULL,
    CONSTRAINT ck_documento_fornecedor CHECK (
        documento_fornecedor ~ '^([0-9]{11}|[0-9]{14})$'
    )
);

CREATE TABLE embedding_despesa (
    id_embedding    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_despesa      BIGINT NOT NULL UNIQUE REFERENCES despesa_campanha(id_despesa)
                    ON UPDATE RESTRICT ON DELETE CASCADE,
    vetor            VECTOR(768) NOT NULL,
    nome_modelo      VARCHAR(150) NOT NULL,
    data_geracao     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prompt_auditoria_log (
    id_log                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidatura           BIGINT NOT NULL REFERENCES candidatura(id_candidatura)
                             ON UPDATE RESTRICT ON DELETE RESTRICT,
    texto_prompt             TEXT NOT NULL,
    resposta_llm             TEXT NOT NULL,
    score_anomalia_predito   NUMERIC(4,3) NOT NULL
                             CHECK (score_anomalia_predito BETWEEN 0.00 AND 1.00),
    data_hora_execucao       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- HNSW com distância de cosseno. Disponível conforme versão de pgvector.
CREATE INDEX idx_embedding_despesa_hnsw_cosine
    ON embedding_despesa USING hnsw (vetor vector_cosine_ops);

CREATE INDEX idx_despesa_campanha_candidatura
    ON despesa_campanha (id_candidatura);

CREATE INDEX idx_prompt_log_candidatura_data
    ON prompt_auditoria_log (id_candidatura, data_hora_execucao DESC);

-- Contexto estruturado para montagem do prompt. A view não executa o LLM
-- nem realiza, sozinha, recuperação semântica; ela organiza dados relacionais.
CREATE OR REPLACE VIEW vw_contexto_prompt_llm AS
SELECT
    c.id_candidatura,
    c.nome_completo AS nome_candidato,
    c.genero,
    c.cargo_pretendido,
    c.total_votos,
    p.numero_partido,
    p.sigla AS sigla_partido,
    p.nome_completo AS nome_partido,
    d.id_despesa,
    d.documento_fornecedor,
    d.nome_fornecedor,
    d.valor_despesa,
    d.data_contratacao,
    d.texto_bruto,
    concat_ws(
        E'\\n',
        'CANDIDATURA: ' || c.nome_completo,
        'GÊNERO: ' || c.genero,
        'CARGO: ' || c.cargo_pretendido,
        'TOTAL DE VOTOS: ' || c.total_votos::TEXT,
        'PARTIDO: ' || p.sigla || ' - ' || p.nome_completo,
        'DESPESA ID: ' || d.id_despesa::TEXT,
        'FORNECEDOR: ' || d.nome_fornecedor,
        'DOCUMENTO FORNECEDOR: ' || d.documento_fornecedor,
        'VALOR: R$ ' || to_char(d.valor_despesa, 'FM999G999G990D00'),
        'DATA: ' || d.data_contratacao::TEXT,
        'DESCRIÇÃO ORIGINAL: ' || d.texto_bruto
    ) AS payload_contexto_llm
FROM candidatura c
JOIN partido p ON p.id_partido = c.id_partido
LEFT JOIN despesa_campanha d ON d.id_candidatura = c.id_candidatura;

